-- Keep the rows already in neondb. Do not re-run 004_public_banking.sql for this.
-- bank_id and a_type_id are assigned when the name is inserted.
-- bank_name, type_name, and headers are unique ignoring case.
-- Fill any blank names or duplicate spellings before running the unique indexes.

ALTER TABLE public.banks_d
ALTER COLUMN bank_id ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.account_types_d
ALTER COLUMN a_type_id ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.banks_d
ALTER COLUMN bank_name SET NOT NULL;

ALTER TABLE public.bank_templates_f
ALTER COLUMN headers SET NOT NULL;

SELECT SETVAL(
    PG_GET_SERIAL_SEQUENCE('public.banks_d', 'bank_id'),
    (SELECT COALESCE(MAX(bank_id), 1) FROM public.banks_d),
    (SELECT EXISTS(SELECT 1 FROM public.banks_d))
);

SELECT SETVAL(
    PG_GET_SERIAL_SEQUENCE('public.account_types_d', 'a_type_id'),
    (SELECT COALESCE(MAX(a_type_id), 1) FROM public.account_types_d),
    (SELECT EXISTS(SELECT 1 FROM public.account_types_d))
);

CREATE UNIQUE INDEX banks_d_bank_name_lower_idx
ON public.banks_d (LOWER(bank_name));

CREATE UNIQUE INDEX account_types_d_type_name_lower_idx
ON public.account_types_d (LOWER(type_name));

CREATE UNIQUE INDEX bank_templates_f_headers_lower_idx
ON public.bank_templates_f (LOWER(headers));
