    SELECT session_row.tenant_id, session_row.user_id
    INTO v_tenant, v_user
    FROM public.require_session() AS session_row;
    v_auto := public.transfer_auto_enabled(v_tenant, v_user);
    RETURN JSONB_BUILD_OBJECT(
        'auto_link_transfers', v_auto,
        'links', COALESCE(
            (
                SELECT JSONB_AGG(
                    JSONB_BUILD_OBJECT(
                        'link_hash', link.link_hash,
                        'transfer_type', link.transfer_type,
                        'source', link.source,
                        'reviewed', link.reviewed_at IS NOT NULL,
                        'reviewed_at', link.reviewed_at,
                        'txn_date', link.txn_date,
                        'amount', link.amount,
                        'amount_difference', link.amount_difference,
                        'match_candidates', link.match_candidates,
                        'created_at', link.created_at,
                        'sending', public.transfer_side(v_tenant, v_user, link.sending_hash),
                        'receiving', public.transfer_side(v_tenant, v_user, link.receiving_hash)
                    )
                    ORDER BY (link.reviewed_at IS NULL) DESC, link.txn_date DESC, link.link_hash
                )
                FROM public.inter_accounts_d AS link
                WHERE link.tenant_id = v_tenant AND link.user_id = v_user AND link.status = 'active'
            ),
            '[]'::JSONB
        ),
        'suggestions', public.transfer_detect(v_tenant, v_user, FALSE) -> 'pairs'
    );
END
