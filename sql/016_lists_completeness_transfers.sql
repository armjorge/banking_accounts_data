-- Attribute lists, upload completeness and transfer links between accounts
-- (see docs/dimensions.md, docs/transfers.md and docs/graphql.md).
--
--   * list_f / list_d: user lists (list_f) and their items (list_d), shared by debit and
--     credit. attribute_settings_d binds attribute_1..3 to a list or leaves them free
--     text. A list-bound attribute stores the item_id (debit_d / credit_d
--     attribute_N_item_id), so renaming an item renames it on every movement. Every
--     reader (dimension_rows, graphql_rows, the Sheets add-on) gets the item NAME.
--   * upload_completeness: per account, the current open period plus the two closed
--     periods before it, scored by CSV and PDF uploads; rolled up per bank and kind.
--   * inter_accounts_d: links a sending movement (debit, money out) with a receiving one
--     (debit money in, or a credit-card payment). Detection follows the same-date,
--     same-amount, opposite-direction rule (same bank first, then across banks) and
--     creates links flagged source = 'auto'; the user can confirm, unlink, or link any
--     two rows by hand. dimension_rows and graphql_rows expose is_internal_transfer.
--
-- Safe to run more than once. Requires 015. Apply on Neon by hand after 015.

-- =============================================================================
-- 1. Lists, list items and attribute settings
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.list_f (
    list_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id UUID NOT NULL,
    user_id UUID NOT NULL,
    list_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID,
    updated_at TIMESTAMPTZ,
    updated_by UUID,
    CONSTRAINT list_f_pkey PRIMARY KEY (list_id),
    CONSTRAINT list_f_owner_key UNIQUE (list_id, tenant_id, user_id),
    CONSTRAINT list_f_tenant_user_fkey
    FOREIGN KEY (tenant_id, user_id) REFERENCES public.tenant_users (tenant_id, user_id),
    CONSTRAINT list_f_name_check CHECK (LENGTH(list_name) BETWEEN 1 AND 100 AND list_name = BTRIM(list_name))
);

CREATE UNIQUE INDEX IF NOT EXISTS list_f_name_idx
ON public.list_f (tenant_id, user_id, LOWER(list_name));

CREATE TABLE IF NOT EXISTS public.list_d (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    list_id BIGINT NOT NULL,
    tenant_id UUID NOT NULL,
    user_id UUID NOT NULL,
    item_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID,
    updated_at TIMESTAMPTZ,
    updated_by UUID,
    CONSTRAINT list_d_pkey PRIMARY KEY (item_id),
    CONSTRAINT list_d_list_item_key UNIQUE (list_id, item_id),
    CONSTRAINT list_d_list_fkey
    FOREIGN KEY (list_id, tenant_id, user_id) REFERENCES public.list_f (list_id, tenant_id, user_id)
    ON DELETE CASCADE,
    CONSTRAINT list_d_name_check CHECK (LENGTH(item_name) BETWEEN 1 AND 500 AND item_name = BTRIM(item_name))
);

CREATE UNIQUE INDEX IF NOT EXISTS list_d_name_idx
ON public.list_d (list_id, LOWER(item_name));
CREATE INDEX IF NOT EXISTS list_d_tenant_idx ON public.list_d (tenant_id, user_id);

COMMENT ON TABLE public.list_f IS
'User lists for movement attributes (sql/016), shared by debit_d and credit_d.';
COMMENT ON TABLE public.list_d IS
'Items of a list_f list. debit_d / credit_d store item_id, so a rename shows everywhere.';

-- How each of the three attributes works for a user: free text (list_id NULL) or a list.
CREATE TABLE IF NOT EXISTS public.attribute_settings_d (
    tenant_id UUID NOT NULL,
    user_id UUID NOT NULL,
    slot SMALLINT NOT NULL,
    label TEXT,
    list_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID,
    updated_at TIMESTAMPTZ,
    updated_by UUID,
    CONSTRAINT attribute_settings_d_pkey PRIMARY KEY (tenant_id, user_id, slot),
    CONSTRAINT attribute_settings_d_tenant_user_fkey
    FOREIGN KEY (tenant_id, user_id) REFERENCES public.tenant_users (tenant_id, user_id),
    CONSTRAINT attribute_settings_d_list_fkey
    FOREIGN KEY (list_id, tenant_id, user_id) REFERENCES public.list_f (list_id, tenant_id, user_id),
    CONSTRAINT attribute_settings_d_slot_check CHECK (slot BETWEEN 1 AND 3),
    CONSTRAINT attribute_settings_d_label_check CHECK (COALESCE(LENGTH(label), 0) <= 60)
);

COMMENT ON TABLE public.attribute_settings_d IS
'Per user: label of attribute_1..3 and the list it is bound to (NULL list_id = free text).';

-- Per user switches for sql/016 (auto-created transfer links).
CREATE TABLE IF NOT EXISTS public.dimension_settings_d (
