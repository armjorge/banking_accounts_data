-- =============================================================================
-- 3. Transfer links between accounts (docs/transfers.md)
-- =============================================================================
-- One row per link. sending_hash: a debit movement with money out (abonos + cargos < 0).
-- receiving_hash: a debit movement with money in (> 0) or a credit-card payment
-- (credit abonos > 0). A movement is in at most one active link.
CREATE TABLE IF NOT EXISTS public.inter_accounts_d (
    link_hash TEXT NOT NULL,
    tenant_id UUID NOT NULL,
    user_id UUID NOT NULL,
    sending_hash TEXT NOT NULL,
    receiving_hash TEXT NOT NULL,
    sending_account_id INTEGER NOT NULL,
    receiving_account_id INTEGER NOT NULL,
    receiving_kind TEXT NOT NULL,
    transfer_type TEXT NOT NULL,
    source TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active',
    txn_date DATE,
    receiving_date DATE,
    amount NUMERIC(14, 2),
    amount_difference NUMERIC(14, 2),
    match_candidates INTEGER,
    reviewed_at TIMESTAMPTZ,
    reviewed_by UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID,
    updated_at TIMESTAMPTZ,
    updated_by UUID,
    CONSTRAINT inter_accounts_d_pkey PRIMARY KEY (link_hash),
    CONSTRAINT inter_accounts_d_tenant_user_fkey
    FOREIGN KEY (tenant_id, user_id) REFERENCES public.tenant_users (tenant_id, user_id),
    CONSTRAINT inter_accounts_d_sending_account_fkey
    FOREIGN KEY (sending_account_id, user_id) REFERENCES public.bank_accounts_d (account_id, user_id)
    ON DELETE CASCADE,
    CONSTRAINT inter_accounts_d_receiving_account_fkey
    FOREIGN KEY (receiving_account_id, user_id) REFERENCES public.bank_accounts_d (account_id, user_id)
    ON DELETE CASCADE,
    CONSTRAINT inter_accounts_d_hash_check CHECK (
        LENGTH(link_hash) = 64 AND LENGTH(sending_hash) = 64 AND LENGTH(receiving_hash) = 64
        AND sending_hash <> receiving_hash
    ),
    CONSTRAINT inter_accounts_d_kind_check CHECK (receiving_kind IN ('debit', 'credit')),
    CONSTRAINT inter_accounts_d_type_check CHECK (transfer_type IN ('same_bank', 'inter_bank')),
    CONSTRAINT inter_accounts_d_source_check CHECK (source IN ('auto', 'manual')),
    CONSTRAINT inter_accounts_d_status_check CHECK (status IN ('active', 'unlinked')),
    CONSTRAINT inter_accounts_d_accounts_check CHECK (sending_account_id <> receiving_account_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS inter_accounts_d_sending_idx
ON public.inter_accounts_d (sending_hash) WHERE status = 'active';
CREATE UNIQUE INDEX IF NOT EXISTS inter_accounts_d_receiving_idx
ON public.inter_accounts_d (receiving_hash) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS inter_accounts_d_tenant_idx ON public.inter_accounts_d (tenant_id, user_id, status);

COMMENT ON TABLE public.inter_accounts_d IS
'Transfer links between two of the user''s accounts (sql/016): sending debit movement -> '
'receiving debit movement or credit-card payment. status unlinked keeps a dismissed pair '
'so detection does not suggest it again.';
COMMENT ON COLUMN public.inter_accounts_d.link_hash IS
'SHA-256 hex of sending_hash || '':'' || receiving_hash.';
COMMENT ON COLUMN public.inter_accounts_d.source IS
'auto = created by detect_transfers (same date, same amount); manual = linked by the user.';
COMMENT ON COLUMN public.inter_accounts_d.reviewed_at IS
'When the user confirmed (or made) the link; NULL on auto links still to review.';
COMMENT ON COLUMN public.inter_accounts_d.match_candidates IS
'Auto links: how many receiving movements matched the rule (more than 1 = check it).';

CREATE OR REPLACE FUNCTION public.transfer_link_hash(p_sending TEXT, p_receiving TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
AS $fn$
    SELECT ENCODE(SHA256(CONVERT_TO(p_sending || ':' || p_receiving, 'UTF8')), 'hex')
$fn$;

-- Each movement with its link side (both rows of a link appear, one per side).
CREATE OR REPLACE VIEW public.movement_transfers_v
WITH (security_invoker = TRUE) AS
SELECT
    link.tenant_id,
    link.user_id,
    link.sending_hash AS row_hash,
    'sending'::TEXT AS transfer_role,
    link.receiving_hash AS counterpart_hash,
    link.receiving_account_id AS counterpart_account_id,
    link.link_hash,
    link.transfer_type,
    link.source,
    link.reviewed_at
FROM public.inter_accounts_d AS link
WHERE link.status = 'active'
UNION ALL
SELECT
    link.tenant_id,
    link.user_id,
    link.receiving_hash AS row_hash,
    'receiving'::TEXT AS transfer_role,
    link.sending_hash AS counterpart_hash,
    link.sending_account_id AS counterpart_account_id,
    link.link_hash,
    link.transfer_type,
    link.source,
    link.reviewed_at
FROM public.inter_accounts_d AS link
WHERE link.status = 'active';

COMMENT ON VIEW public.movement_transfers_v IS
'Active transfer links, one row per side (row_hash, transfer_role sending/receiving).';

-- Movements that can be one side of a transfer, one row per row_hash (a movement in both
-- the open and the closed book is listed once, closed first). Future rows are excluded.
CREATE OR REPLACE FUNCTION public.transfer_pool(p_tenant UUID, p_user UUID)
RETURNS TABLE (
    row_hash TEXT,
    kind TEXT,
    layer TEXT,
    transfer_role TEXT,
    account_id INTEGER,
    account_number TEXT,
    bank_id INTEGER,
    bank_name TEXT,
    txn_date DATE,
    concept TEXT,
    concept_sk TEXT,
    abs_amount NUMERIC
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $fn$
    SELECT DISTINCT ON (keys.row_hash)
        keys.row_hash,
        keys.kind,
        keys.layer,
        CASE
            WHEN keys.kind = 'debit' AND COALESCE(keys.abonos, 0) + COALESCE(keys.cargos, 0) < 0 THEN 'sending'
            ELSE 'receiving'
        END AS transfer_role,
        keys.account_id,
        keys.account_number,
        keys.bank_id,
        keys.bank_name,
        keys.txn_date,
        keys.concept,
        keys.concept_sk,
        CASE
            WHEN keys.kind = 'debit' THEN ABS(COALESCE(keys.abonos, 0) + COALESCE(keys.cargos, 0))
            ELSE keys.abonos
        END::NUMERIC AS abs_amount
    FROM public.movement_keys_v AS keys
    WHERE
        keys.tenant_id = p_tenant
        AND keys.user_id = p_user
        AND keys.layer IN ('open', 'closed')
        AND (
            (keys.kind = 'debit' AND COALESCE(keys.abonos, 0) + COALESCE(keys.cargos, 0) <> 0)
            OR (keys.kind = 'credit' AND COALESCE(keys.abonos, 0) > 0 AND COALESCE(keys.cargos, 0) = 0)
        )
    ORDER BY keys.row_hash, CASE keys.layer WHEN 'closed' THEN 0 ELSE 1 END
$fn$;

-- Detection (internal; no session). Rule, from the transfer query Jorge uses on debit:
-- a sending movement and a receiving movement of two different accounts with the same
-- txn_date and the same absolute amount. Pass 1 pairs within the same bank, pass 2 the
-- rest across banks. Senders go in (date, amount, account, row) order; each takes the
-- first free receiver (debit before credit, then account, then row_hash). Pairs the user
-- unlinked are never proposed again. p_create = TRUE stores the pairs (source 'auto',
-- not reviewed) and drops auto links nobody reviewed whose movements are gone; FALSE
-- only returns them.
CREATE OR REPLACE FUNCTION public.transfer_detect(p_tenant UUID, p_user UUID, p_create BOOLEAN)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_pass INTEGER;
    v_sender RECORD;
    v_receiver RECORD;
    v_candidates INTEGER;
    v_used TEXT [];
    v_pairs JSONB := '[]'::JSONB;
    v_removed INTEGER := 0;
    v_created INTEGER := 0;
BEGIN
    DROP TABLE IF EXISTS pg_temp.transfer_pool_tmp;
    CREATE TEMP TABLE transfer_pool_tmp ON COMMIT DROP AS
    SELECT * FROM public.transfer_pool(p_tenant, p_user);
    CREATE INDEX ON pg_temp.transfer_pool_tmp (transfer_role, txn_date, abs_amount);

    IF p_create THEN
        DELETE FROM public.inter_accounts_d AS link
        WHERE
            link.tenant_id = p_tenant
            AND link.user_id = p_user
            AND link.source = 'auto'
            AND link.status = 'active'
            AND link.reviewed_at IS NULL
            AND (
                NOT EXISTS (SELECT 1 FROM pg_temp.transfer_pool_tmp AS pool WHERE pool.row_hash = link.sending_hash)
                OR NOT EXISTS (
                    SELECT 1 FROM pg_temp.transfer_pool_tmp AS pool WHERE pool.row_hash = link.receiving_hash
                )
            );
        GET DIAGNOSTICS v_removed = ROW_COUNT;
    END IF;

    SELECT COALESCE(ARRAY_AGG(side.row_hash), ARRAY[]::TEXT [])
    INTO v_used
    FROM public.movement_transfers_v AS side
    WHERE side.tenant_id = p_tenant AND side.user_id = p_user;

    FOR v_pass IN 1..2 LOOP
        FOR v_sender IN
            SELECT pool.*
            FROM pg_temp.transfer_pool_tmp AS pool
            WHERE pool.transfer_role = 'sending'
            ORDER BY pool.txn_date, pool.abs_amount, pool.account_id, pool.row_hash
        LOOP
            CONTINUE WHEN v_sender.row_hash = ANY(v_used);
            SELECT COUNT(*) INTO v_candidates
            FROM pg_temp.transfer_pool_tmp AS pool
            WHERE
                pool.transfer_role = 'receiving'
                AND pool.txn_date = v_sender.txn_date
                AND pool.abs_amount = v_sender.abs_amount
                AND pool.account_id <> v_sender.account_id
                AND NOT (pool.row_hash = ANY(v_used));
            SELECT pool.*
            INTO v_receiver
            FROM pg_temp.transfer_pool_tmp AS pool
            WHERE
                pool.transfer_role = 'receiving'
                AND pool.txn_date = v_sender.txn_date
                AND pool.abs_amount = v_sender.abs_amount
                AND pool.account_id <> v_sender.account_id
                AND (
                    (v_pass = 1 AND pool.bank_id = v_sender.bank_id)
                    OR (v_pass = 2 AND pool.bank_id IS DISTINCT FROM v_sender.bank_id)
                )
                AND NOT (pool.row_hash = ANY(v_used))
                AND NOT EXISTS (
                    SELECT 1 FROM public.inter_accounts_d AS dismissed
                    WHERE dismissed.link_hash = public.transfer_link_hash(v_sender.row_hash, pool.row_hash)
                )
            ORDER BY CASE pool.kind WHEN 'debit' THEN 0 ELSE 1 END, pool.account_id, pool.row_hash
            LIMIT 1;
            CONTINUE WHEN v_receiver.row_hash IS NULL;

            v_used := v_used || ARRAY[v_sender.row_hash, v_receiver.row_hash];
            v_pairs := v_pairs || JSONB_BUILD_ARRAY(JSONB_BUILD_OBJECT(
                'link_hash', public.transfer_link_hash(v_sender.row_hash, v_receiver.row_hash),
                'sending_hash', v_sender.row_hash,
                'receiving_hash', v_receiver.row_hash,
                'transfer_type', CASE WHEN v_pass = 1 THEN 'same_bank' ELSE 'inter_bank' END,
                'txn_date', v_sender.txn_date,
                'amount', v_sender.abs_amount,
                'match_candidates', v_candidates,
                'sending', JSONB_BUILD_OBJECT(
                    'account_number', v_sender.account_number, 'bank_name', v_sender.bank_name,
                    'concept', v_sender.concept, 'kind', v_sender.kind, 'layer', v_sender.layer
                ),
                'receiving', JSONB_BUILD_OBJECT(
                    'account_number', v_receiver.account_number, 'bank_name', v_receiver.bank_name,
                    'concept', v_receiver.concept, 'kind', v_receiver.kind, 'layer', v_receiver.layer
                )
            ));
            IF p_create THEN
                INSERT INTO public.inter_accounts_d (
                    link_hash, tenant_id, user_id, sending_hash, receiving_hash,
                    sending_account_id, receiving_account_id, receiving_kind, transfer_type, source,
                    status, txn_date, receiving_date, amount, amount_difference, match_candidates, created_by
                )
                VALUES (
                    public.transfer_link_hash(v_sender.row_hash, v_receiver.row_hash), p_tenant, p_user,
                    v_sender.row_hash, v_receiver.row_hash, v_sender.account_id, v_receiver.account_id,
                    v_receiver.kind, CASE WHEN v_pass = 1 THEN 'same_bank' ELSE 'inter_bank' END, 'auto',
                    'active', v_sender.txn_date, v_receiver.txn_date, v_sender.abs_amount, 0, v_candidates, p_user
                )
                ON CONFLICT (link_hash) DO NOTHING;
                v_created := v_created + 1;
            END IF;
        END LOOP;
    END LOOP;

    DROP TABLE IF EXISTS pg_temp.transfer_pool_tmp;
    RETURN JSONB_BUILD_OBJECT(
        'created', v_created,
        'removed', v_removed,
        'pairs', v_pairs
    );
END
$fn$;

