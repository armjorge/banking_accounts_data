-- Page: movements that could be the other side of p_row_hash (opposite role, another
-- account, not linked yet), closest first: same amount, then nearest date. p_search
-- filters on concept, account or bank; without it only +-45 days are listed.
CREATE OR REPLACE FUNCTION public.transfer_partners(
    p_row_hash TEXT,
    p_search TEXT DEFAULT NULL,
    p_limit INTEGER DEFAULT 30
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_tenant UUID;
    v_user UUID;
    v_row RECORD;
    v_search TEXT := NULLIF(BTRIM(COALESCE(p_search, '')), '');
BEGIN
    SELECT session_row.tenant_id, session_row.user_id
    INTO v_tenant, v_user
    FROM public.require_session() AS session_row;
    SELECT * INTO v_row FROM public.transfer_pool(v_tenant, v_user) AS pool WHERE pool.row_hash = p_row_hash;
    IF v_row.row_hash IS NULL THEN
        RAISE EXCEPTION 'This movement cannot be part of a transfer' USING ERRCODE = 'P0002';
    END IF;
    RETURN JSONB_BUILD_OBJECT(
        'row', TO_JSONB(v_row),
        'partners', COALESCE(
            (
                SELECT JSONB_AGG(TO_JSONB(picked) ORDER BY picked.rank_amount, picked.days_apart, picked.txn_date DESC)
                FROM (
                    SELECT
                        pool.*,
                        CASE WHEN pool.abs_amount = v_row.abs_amount THEN 0 ELSE 1 END AS rank_amount,
                        ABS(pool.txn_date - v_row.txn_date) AS days_apart
                    FROM public.transfer_pool(v_tenant, v_user) AS pool
                    WHERE
                        pool.transfer_role <> v_row.transfer_role
                        AND pool.account_id <> v_row.account_id
                        AND NOT EXISTS (
                            SELECT 1 FROM public.movement_transfers_v AS side
                            WHERE side.row_hash = pool.row_hash AND side.tenant_id = v_tenant
                        )
                        AND (
                            (v_search IS NULL AND ABS(pool.txn_date - v_row.txn_date) <= 45)
                            OR pool.concept ILIKE '%' || v_search || '%'
                            OR pool.account_number ILIKE '%' || v_search || '%'
                            OR pool.bank_name ILIKE '%' || v_search || '%'
                        )
                    ORDER BY rank_amount, days_apart, pool.txn_date DESC
                    LIMIT LEAST(GREATEST(COALESCE(p_limit, 30), 1), 100)
                ) AS picked
            ),
            '[]'::JSONB
        )
    );
END
$fn$;

-- Auto-link new movements as they are stored (only for users with auto links on). Never
-- blocks an upload: a failure is logged as a warning and the upload continues.
CREATE OR REPLACE FUNCTION public.detect_transfers_after_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_owner RECORD;
BEGIN
    FOR v_owner IN SELECT DISTINCT added.tenant_id, added.user_id FROM added_rows AS added
    LOOP
        CONTINUE WHEN NOT public.transfer_auto_enabled(v_owner.tenant_id, v_owner.user_id);
        BEGIN
            PERFORM public.transfer_detect(v_owner.tenant_id, v_owner.user_id, TRUE);
        EXCEPTION WHEN OTHERS THEN
            RAISE WARNING 'transfer detection skipped: %', SQLERRM;
        END;
    END LOOP;
    RETURN NULL;
END
$fn$;

DO $do$
DECLARE
    v_table TEXT;
BEGIN
    FOREACH v_table IN ARRAY ARRAY[
        'master_debit_closed_f', 'master_debit_open_f', 'master_credit_closed_f', 'master_credit_open_f'
    ]
    LOOP
        EXECUTE FORMAT('DROP TRIGGER IF EXISTS %I ON public.%I', v_table || '_transfer_links', v_table);
        EXECUTE FORMAT(
            'CREATE TRIGGER %I AFTER INSERT ON public.%I
            REFERENCING NEW TABLE AS added_rows
            FOR EACH STATEMENT EXECUTE FUNCTION public.detect_transfers_after_insert()',
            v_table || '_transfer_links', v_table
        );
    END LOOP;
END
