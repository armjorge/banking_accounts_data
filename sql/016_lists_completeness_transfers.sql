CREATE OR REPLACE FUNCTION public.list_clean_name(p_name TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
AS $fn$
    SELECT NULLIF(BTRIM(REGEXP_REPLACE(COALESCE(p_name, ''), '\s+', ' ', 'g')), '')
$fn$;

-- Lists, their items (with how many movements use each) and the three attribute slots.
CREATE OR REPLACE FUNCTION public.list_catalog()
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_tenant UUID;
    v_user UUID;
BEGIN
    SELECT session_row.tenant_id, session_row.user_id
    INTO v_tenant, v_user
    FROM public.require_session() AS session_row;

    RETURN JSONB_BUILD_OBJECT(
        'attributes', (
            SELECT JSONB_AGG(
                JSONB_BUILD_OBJECT(
                    'slot', slot.n,
                    'field', 'attribute_' || slot.n,
                    'label', COALESCE(NULLIF(setting.label, ''), 'Attribute ' || slot.n),
                    'custom_label', setting.label,
                    'mode', CASE WHEN setting.list_id IS NULL THEN 'text' ELSE 'list' END,
                    'list_id', setting.list_id,
                    'list_name', bound.list_name
                )
                ORDER BY slot.n
            )
            FROM GENERATE_SERIES(1, 3) AS slot (n)
            LEFT JOIN public.attribute_settings_d AS setting
                ON setting.tenant_id = v_tenant AND setting.user_id = v_user AND setting.slot = slot.n
            LEFT JOIN public.list_f AS bound ON bound.list_id = setting.list_id
        ),
        'lists', COALESCE(
            (
                SELECT JSONB_AGG(
                    JSONB_BUILD_OBJECT(
                        'list_id', list.list_id,
                        'list_name', list.list_name,
                        'slots', COALESCE(
                            (
                                SELECT JSONB_AGG(setting.slot ORDER BY setting.slot)
                                FROM public.attribute_settings_d AS setting
                                WHERE
                                    setting.list_id = list.list_id
                                    AND setting.tenant_id = v_tenant
                                    AND setting.user_id = v_user
                            ),
                            '[]'::JSONB
                        ),
                        'items', COALESCE(
                            (
                                SELECT JSONB_AGG(
                                    JSONB_BUILD_OBJECT(
                                        'item_id', item.item_id,
                                        'item_name', item.item_name,
                                        'used', (
                                            SELECT COUNT(*)
                                            FROM public.movement_attributes_v AS used
                                            WHERE
                                                used.tenant_id = v_tenant
                                                AND used.user_id = v_user
                                                AND item.item_id IN (
                                                    used.attribute_1_item_id,
                                                    used.attribute_2_item_id,
                                                    used.attribute_3_item_id
                                                )
                                        )
                                    )
                                    ORDER BY LOWER(item.item_name)
                                )
                                FROM public.list_d AS item
                                WHERE item.list_id = list.list_id
                            ),
                            '[]'::JSONB
                        )
                    )
                    ORDER BY LOWER(list.list_name)
                )
                FROM public.list_f AS list
                WHERE list.tenant_id = v_tenant AND list.user_id = v_user
            ),
            '[]'::JSONB
        )
    );
END
$fn$;

CREATE OR REPLACE FUNCTION public.create_list(p_list_name TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_tenant UUID;
    v_user UUID;
    v_name TEXT := public.list_clean_name(p_list_name);
    v_list RECORD;
BEGIN
    SELECT session_row.tenant_id, session_row.user_id
    INTO v_tenant, v_user
    FROM public.require_session() AS session_row;
    IF v_name IS NULL OR LENGTH(v_name) > 100 THEN
        RAISE EXCEPTION 'A list name needs 1 to 100 characters' USING ERRCODE = '22023';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.list_f AS list
        WHERE list.tenant_id = v_tenant AND list.user_id = v_user AND LOWER(list.list_name) = LOWER(v_name)
    ) THEN
        RAISE EXCEPTION 'A list named "%" already exists', v_name USING ERRCODE = '23505';
    END IF;
    IF (SELECT COUNT(*) FROM public.list_f AS list WHERE list.tenant_id = v_tenant AND list.user_id = v_user) >= 50 THEN
        RAISE EXCEPTION 'At most 50 lists per user' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.list_f (tenant_id, user_id, list_name, created_by)
    VALUES (v_tenant, v_user, v_name, v_user)
    RETURNING list_f.list_id, list_f.list_name INTO v_list;
    RETURN JSONB_BUILD_OBJECT('list_id', v_list.list_id, 'list_name', v_list.list_name);
END
$fn$;

CREATE OR REPLACE FUNCTION public.rename_list(p_list_id BIGINT, p_list_name TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_tenant UUID;
    v_user UUID;
    v_name TEXT := public.list_clean_name(p_list_name);
BEGIN
    SELECT session_row.tenant_id, session_row.user_id
    INTO v_tenant, v_user
    FROM public.require_session() AS session_row;
    IF v_name IS NULL OR LENGTH(v_name) > 100 THEN
        RAISE EXCEPTION 'A list name needs 1 to 100 characters' USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.list_f AS list
        WHERE list.list_id = p_list_id AND list.tenant_id = v_tenant AND list.user_id = v_user
    ) THEN
        RAISE EXCEPTION 'list not found' USING ERRCODE = 'P0002';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.list_f AS list
        WHERE
            list.tenant_id = v_tenant AND list.user_id = v_user
            AND LOWER(list.list_name) = LOWER(v_name) AND list.list_id <> p_list_id
    ) THEN
        RAISE EXCEPTION 'A list named "%" already exists', v_name USING ERRCODE = '23505';
    END IF;
    UPDATE public.list_f
    SET list_name = v_name, updated_at = NOW(), updated_by = v_user
    WHERE list_id = p_list_id;
    RETURN JSONB_BUILD_OBJECT('list_id', p_list_id, 'list_name', v_name);
END
$fn$;

-- Internal: the item of p_list_id named p_name (case-insensitive), created when missing.
CREATE OR REPLACE FUNCTION public.list_item_ensure(
    p_tenant UUID,
    p_user UUID,
    p_list_id BIGINT,
    p_name TEXT
) RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_name TEXT := public.list_clean_name(p_name);
    v_item BIGINT;
BEGIN
    IF v_name IS NULL THEN
        RETURN NULL;
    END IF;
    IF LENGTH(v_name) > 500 THEN
        RAISE EXCEPTION 'An item name can have at most 500 characters' USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.list_f AS list
        WHERE list.list_id = p_list_id AND list.tenant_id = p_tenant AND list.user_id = p_user
    ) THEN
        RAISE EXCEPTION 'list not found' USING ERRCODE = 'P0002';
    END IF;
    INSERT INTO public.list_d (list_id, tenant_id, user_id, item_name, created_by)
    VALUES (p_list_id, p_tenant, p_user, v_name, p_user)
    ON CONFLICT (list_id, (LOWER(item_name))) DO NOTHING
    RETURNING list_d.item_id INTO v_item;
    IF v_item IS NULL THEN
        SELECT item.item_id INTO v_item
        FROM public.list_d AS item
        WHERE item.list_id = p_list_id AND LOWER(item.item_name) = LOWER(v_name);
    END IF;
    RETURN v_item;
END
$fn$;

-- Adds an item (returns the existing one when the name is already in the list).
CREATE OR REPLACE FUNCTION public.add_list_item(p_list_id BIGINT, p_item_name TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_tenant UUID;
    v_user UUID;
    v_item BIGINT;
BEGIN
    SELECT session_row.tenant_id, session_row.user_id
    INTO v_tenant, v_user
    FROM public.require_session() AS session_row;
    IF public.list_clean_name(p_item_name) IS NULL THEN
        RAISE EXCEPTION 'An item name needs at least 1 character' USING ERRCODE = '22023';
    END IF;
    IF (SELECT COUNT(*) FROM public.list_d AS item WHERE item.list_id = p_list_id) >= 1000 THEN
        RAISE EXCEPTION 'At most 1000 items per list' USING ERRCODE = '22023';
    END IF;
    v_item := public.list_item_ensure(v_tenant, v_user, p_list_id, p_item_name);
    RETURN (
        SELECT JSONB_BUILD_OBJECT('item_id', item.item_id, 'list_id', item.list_id, 'item_name', item.item_name)
        FROM public.list_d AS item
        WHERE item.item_id = v_item
    );
END
$fn$;

