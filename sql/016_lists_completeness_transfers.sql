-- Page: link any two movements of two different accounts. The order does not matter: the
-- money-out debit row is the sending side; the other must be money in (debit) or a card
-- payment (credit abonos). Amounts and dates may differ (amount_difference is kept).
CREATE OR REPLACE FUNCTION public.link_transfer(p_row_a TEXT, p_row_b TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
    v_tenant UUID;
    v_user UUID;
    v_a RECORD;
    v_b RECORD;
    v_send RECORD;
    v_recv RECORD;
    v_hash TEXT;
BEGIN
    SELECT session_row.tenant_id, session_row.user_id
    INTO v_tenant, v_user
    FROM public.require_session() AS session_row;

    SELECT * INTO v_a FROM public.transfer_pool(v_tenant, v_user) AS pool WHERE pool.row_hash = p_row_a;
    SELECT * INTO v_b FROM public.transfer_pool(v_tenant, v_user) AS pool WHERE pool.row_hash = p_row_b;
    IF v_a.row_hash IS NULL OR v_b.row_hash IS NULL THEN
        RAISE EXCEPTION 'Pick two open or closed movements with an amount (installment plans cannot be linked)'
        USING ERRCODE = 'P0002';
    END IF;
    IF v_a.transfer_role = v_b.transfer_role THEN
        RAISE EXCEPTION 'A transfer needs one money-out debit movement and one money-in movement or card payment'
        USING ERRCODE = '22023';
    END IF;
    IF v_a.account_id = v_b.account_id THEN
        RAISE EXCEPTION 'Both movements are in the same account' USING ERRCODE = '22023';
    END IF;
    IF v_a.transfer_role = 'sending' THEN
        v_send := v_a;
        v_recv := v_b;
    ELSE
        v_send := v_b;
        v_recv := v_a;
    END IF;
    v_hash := public.transfer_link_hash(v_send.row_hash, v_recv.row_hash);
    IF EXISTS (
        SELECT 1 FROM public.inter_accounts_d AS link
        WHERE
            link.status = 'active' AND link.link_hash <> v_hash
            AND (link.sending_hash IN (v_send.row_hash, v_recv.row_hash)
                OR link.receiving_hash IN (v_send.row_hash, v_recv.row_hash))
    ) THEN
        RAISE EXCEPTION 'One of the movements is already linked; unlink it first' USING ERRCODE = '23505';
    END IF;

    INSERT INTO public.inter_accounts_d AS link (
        link_hash, tenant_id, user_id, sending_hash, receiving_hash,
        sending_account_id, receiving_account_id, receiving_kind, transfer_type, source,
        status, txn_date, receiving_date, amount, amount_difference, reviewed_at, reviewed_by, created_by
    )
    VALUES (
        v_hash, v_tenant, v_user, v_send.row_hash, v_recv.row_hash, v_send.account_id, v_recv.account_id,
        v_recv.kind,
        CASE WHEN v_send.bank_id = v_recv.bank_id THEN 'same_bank' ELSE 'inter_bank' END,
        'manual', 'active', v_send.txn_date, v_recv.txn_date, v_send.abs_amount,
        v_recv.abs_amount - v_send.abs_amount, NOW(), v_user, v_user
    )
    ON CONFLICT (link_hash) DO UPDATE
    SET
        status = 'active',
        source = 'manual',
        reviewed_at = NOW(),
        reviewed_by = v_user,
        updated_at = NOW(),
        updated_by = v_user
    WHERE link.tenant_id = v_tenant AND link.user_id = v_user;

    RETURN JSONB_BUILD_OBJECT(
        'link_hash', v_hash,
        'sending_hash', v_send.row_hash,
        'receiving_hash', v_recv.row_hash,
        'transfer_type', CASE WHEN v_send.bank_id = v_recv.bank_id THEN 'same_bank' ELSE 'inter_bank' END,
        'source', 'manual'
    );
END
$fn$;

