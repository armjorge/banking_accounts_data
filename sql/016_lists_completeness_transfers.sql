-- List-bound attributes store the item; the 015 text columns stay for free-text slots.
ALTER TABLE public.debit_d ADD COLUMN IF NOT EXISTS attribute_1_item_id BIGINT;
ALTER TABLE public.debit_d ADD COLUMN IF NOT EXISTS attribute_2_item_id BIGINT;
ALTER TABLE public.debit_d ADD COLUMN IF NOT EXISTS attribute_3_item_id BIGINT;
ALTER TABLE public.credit_d ADD COLUMN IF NOT EXISTS attribute_1_item_id BIGINT;
ALTER TABLE public.credit_d ADD COLUMN IF NOT EXISTS attribute_2_item_id BIGINT;
ALTER TABLE public.credit_d ADD COLUMN IF NOT EXISTS attribute_3_item_id BIGINT;

DO $fk$
DECLARE
    v_table TEXT;
    v_slot INTEGER;
BEGIN
    FOREACH v_table IN ARRAY ARRAY['debit_d', 'credit_d']
    LOOP
        FOR v_slot IN 1..3 LOOP
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = FORMAT('%s_attribute_%s_item_fkey', v_table, v_slot)
            ) THEN
                EXECUTE FORMAT(
                    'ALTER TABLE public.%I ADD CONSTRAINT %I
                    FOREIGN KEY (attribute_%s_item_id) REFERENCES public.list_d (item_id)',
                    v_table, FORMAT('%s_attribute_%s_item_fkey', v_table, v_slot), v_slot
                );
            END IF;
            EXECUTE FORMAT(
                'CREATE INDEX IF NOT EXISTS %I ON public.%I (attribute_%s_item_id)
                WHERE attribute_%s_item_id IS NOT NULL',
                FORMAT('%s_attribute_%s_item_idx', v_table, v_slot), v_table, v_slot, v_slot
            );
        END LOOP;
    END LOOP;
END
$fk$;

